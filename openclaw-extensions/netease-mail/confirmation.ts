import { randomUUID } from 'node:crypto';

import {
  failureCode, MAIL_CONFIRMATION_MS, MAIL_FAILURE_CODES, MailAction, MailCode, type MailResult, mailResult, MailStatus, MailTool, payload, record, responseCode, responseData,
} from './protocol';

interface Pending {
  id: string; toolCallId: string; grantId: string; expiresAt: number;
  resolve: (action: typeof MailAction[keyof typeof MailAction]) => void;
}
export interface MailOperation {
  tool: string; toolCallId: string; grantId: string; args: Record<string, unknown>;
  assertGrant: () => void;
  call: (tool: string, args: Record<string, unknown>, signal?: AbortSignal) => Promise<unknown>;
  summary: Record<string, unknown>;
  signal?: AbortSignal;
  onUpdate?: (result: MailResult) => void;
}

/** Frozen arguments/token remain in gateway memory and are never returned to the model. */
export class MailConfirmations {
  private readonly pending = new Map<string, Pending>();

  invalidate(grantId?: string): void {
    for (const [id, operation] of this.pending) {
      if (operation.grantId === grantId) continue;
      this.pending.delete(id);
      operation.resolve(MailAction.Cancel);
    }
  }

  status(id: string, toolCallId: string, grantId?: string): boolean {
    const item = this.pending.get(id);
    return Boolean(item && item.toolCallId === toolCallId && item.grantId === grantId && item.expiresAt > Date.now());
  }

  resolve(id: string, toolCallId: string, action: unknown, grantId?: string): boolean {
    if (action !== MailAction.Confirm && action !== MailAction.Cancel) return false;
    if (!this.status(id, toolCallId, grantId)) return false;
    const item = this.pending.get(id)!;
    this.pending.delete(id); // Consume before resolving: duplicate clicks cannot repeat a write.
    item.resolve(action);
    return true;
  }

  async execute(operation: MailOperation): Promise<MailResult> {
    // Do not accept model-supplied approvals or tokens, even if extra arguments
    // bypass schema validation. Stable request_id is generated by the host.
    const args = structuredClone(operation.args);
    delete args.confirmation_token;
    delete args.confirmed;
    args.request_id = randomUUID();
    operation.assertGrant();
    let prepared: Record<string, unknown>;
    try { prepared = payload(await operation.call(operation.tool, args, operation.signal)); }
    catch (error) { return mailResult({ code: failureCode(error), status: MailStatus.Failed,
      instruction: 'Mail service unavailable. Do not automatically retry.' }, true); }
    const data = responseData(prepared);
    const code = responseCode(prepared);
    if (code !== MailCode.Confirmation) {
      // A service that no longer implements prepare/confirm is incompatible.
      // Do not perform another call, and never assume a write did not happen.
      const knownFailure = MAIL_FAILURE_CODES.has(code);
      return mailResult({ ...(knownFailure || code === MailCode.OutcomeUnknown ? { code } : {}), status: knownFailure ? MailStatus.Failed : MailStatus.Unknown,
        operation_summary: operation.summary, request_id: args.request_id,
        operation_id: typeof data.operation_id === 'string' ? data.operation_id : undefined,
        ...(!knownFailure ? { instruction: 'Outcome unknown. Do not retry or create a new request. Reconcile the original request with the email service.' } : {}) }, true);
    }
    const token = data.confirmation_token;
    if (typeof token !== 'string' || !token || !operation.onUpdate) {
      return mailResult({ code: MailCode.Invalid, status: MailStatus.Failed }, true);
    }
    const remoteExpiry = typeof data.expires_at === 'number'
      ? (data.expires_at < 1e12 ? data.expires_at * 1000 : data.expires_at)
      : typeof data.expires_at === 'string' ? Date.parse(data.expires_at) : NaN;
    const expiresAt = Math.min(Date.now() + MAIL_CONFIRMATION_MS, Number.isFinite(remoteExpiry) ? remoteExpiry : Infinity);
    if (expiresAt <= Date.now()) return mailResult({ status: MailStatus.Expired });
    const id = randomUUID();
    let timer: ReturnType<typeof setTimeout> | undefined;
    let abort: (() => void) | undefined;
    try {
      const action = await new Promise<string>(resolve => {
        this.pending.set(id, { id, toolCallId: operation.toolCallId, grantId: operation.grantId, expiresAt, resolve });
        timer = setTimeout(() => resolve(MailStatus.Expired), expiresAt - Date.now());
        abort = () => resolve(MailAction.Cancel);
        operation.signal?.addEventListener('abort', abort, { once: true });
        if (operation.signal?.aborted) { abort(); return; }
        operation.onUpdate!(mailResult({ code: MailCode.Confirmation, data: {
          confirmation_id: id, operation_summary: operation.summary, expires_at: expiresAt,
        } }));
      });
      this.pending.delete(id);
      if (action !== MailAction.Confirm) return mailResult({ status: action === MailStatus.Expired ? MailStatus.Expired : MailStatus.Cancelled,
        operation_summary: operation.summary });
      operation.assertGrant();
      if (Date.now() >= expiresAt) return mailResult({ status: MailStatus.Expired, operation_summary: operation.summary });
      try {
        // Exactly one execution attempt. A timeout is ambiguous, never retried.
        const raw = await operation.call(operation.tool, { ...args, confirmation_token: token }, operation.signal);
        const result = payload(raw);
        const resultData = responseData(result);
        const resultCode = responseCode(result);
        const failed = MAIL_FAILURE_CODES.has(resultCode);
        const messageId = typeof resultData.message_id === 'string' && resultData.message_id.trim() ? resultData.message_id : undefined;
        const savedSentMid = typeof resultData.saved_sent_mid === 'string' && resultData.saved_sent_mid.trim() ? resultData.saved_sent_mid : undefined;
        const sendsMail = operation.tool === MailTool.Send || operation.tool === MailTool.Reply || operation.tool === MailTool.Forward;
        const trashesMail = operation.tool === MailTool.Trash;
        const accepted = !record(raw)?.isError && (resultCode === 0 || resultCode === 200)
          && (trashesMail ? Boolean(messageId && messageId === args.message_id) : Boolean(messageId || (sendsMail && savedSentMid)));
        // saved_sent_mid identifies the saved Sent copy, not a full MCP
        // message_id or proof of delivery. Preserve it and report submission.
        // Return only receipt metadata; unknown or malformed responses after a
        // write must not invite a retry or claim success.
        return mailResult({ ...(failed || resultCode === MailCode.OutcomeUnknown ? { code: resultCode } : {}), message_id: messageId,
          saved_sent_mid: sendsMail ? savedSentMid : undefined,
          operation_id: typeof resultData.operation_id === 'string' ? resultData.operation_id : undefined,
          status: failed ? MailStatus.Failed : accepted ? trashesMail ? MailStatus.Trashed : MailStatus.Submitted : MailStatus.Unknown,
          ...(accepted ? { instruction: trashesMail
            ? 'The user already clicked the confirmation card and the email service moved this message to Trash. Report that it was moved to Trash, not permanently deleted. No further confirmation or execution is needed. Recovery is available in the email client for 30 days.'
            : 'The user already clicked the confirmation card and the email service accepted the execution. Report that it was submitted. No further approval or send call is needed. Delivery requires separate verification.' } : {}),
          ...(!failed && !accepted ? { instruction: 'The user already approved and execution was attempted. The outcome is unknown. Do not ask for another confirmation or repeat the operation. Report uncertainty even if a mailbox search is empty.' } : {}),
          operation_summary: operation.summary, request_id: args.request_id }, failed);
      } catch (error) {
        const code = failureCode(error);
        if (code !== undefined) return mailResult({ code, status: MailStatus.Failed }, true);
        return mailResult({ status: MailStatus.Unknown, operation_summary: operation.summary, request_id: args.request_id,
          instruction: operation.tool === MailTool.Trash
            ? 'Do not repeat the operation. Check the original folder and Trash or ask the user to verify the outcome.'
            : 'Do not resend. Check the Sent folder or ask the user to verify the outcome.' }, true);
      }
    } catch {
      return mailResult({ code: MailCode.Unauthorized, status: MailStatus.Failed, operation_summary: operation.summary }, true);
    } finally {
      this.pending.delete(id);
      clearTimeout(timer);
      if (abort) operation.signal?.removeEventListener('abort', abort);
    }
  }
}

// OpenClaw registers gateway RPC handlers and per-agent tools in separate
// registries. Both must resolve the same in-memory operation for this profile.
const confirmationsByState = new Map<string, MailConfirmations>();
export function getMailConfirmations(stateDir: string): MailConfirmations {
  let confirmations = confirmationsByState.get(stateDir);
  if (!confirmations) {
    confirmations = new MailConfirmations();
    confirmationsByState.set(stateDir, confirmations);
  }
  return confirmations;
}
