'use strict';

/**
 * Contract between local OpenClaw extensions and the pinned plugin SDK.
 *
 * Extensions under openclaw-extensions/ import `openclaw/plugin-sdk/*` modules
 * that ship inside the OpenClaw runtime. The precompile step keeps those
 * imports external, so a named import the pinned runtime no longer exports only
 * fails when the gateway links the plugin at startup ("does not provide an
 * export named ..."), and the whole plugin silently drops out.
 *
 * This module scans the extensions' SDK imports, reads the export tables of the
 * built runtime with esbuild's metafile (no evaluation, same technique as the
 * plugin SDK bridge) and records them in openclaw-extensions/plugin-sdk-exports.json.
 * Vitest checks the imports against that snapshot on every run, so CI catches a
 * retired export without building the runtime, and re-validates the snapshot
 * against the runtime whenever one is present locally.
 *
 * Usage:
 *   node scripts/openclaw-plugin-sdk-contract.cjs [runtime-dir]          # write snapshot
 *   node scripts/openclaw-plugin-sdk-contract.cjs --check [runtime-dir]  # verify only
 *
 * runtime-dir defaults to vendor/openclaw-runtime/current.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

const { HOST_PEER_PACKAGE_NAME } = require('./openclaw-plugin-host-peer-leftovers.cjs');

const LOG_PREFIX = '[openclaw-plugin-sdk-contract]';
const rootDir = path.resolve(__dirname, '..');

const EXTENSIONS_RELATIVE_DIR = 'openclaw-extensions';
const SNAPSHOT_RELATIVE_PATH = 'openclaw-extensions/plugin-sdk-exports.json';
const SNAPSHOT_COMMENT = 'Generated by scripts/openclaw-plugin-sdk-contract.cjs from the built '
  + 'OpenClaw runtime. Do not edit by hand: rebuild the runtime, then run '
  + '`npm run openclaw:sdk-contract`.';
const PLUGIN_SDK_SPECIFIER_PATTERN = /^(?:openclaw|clawdbot)\/plugin-sdk(\/.+)?$/;
const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx', '.mts', '.cts', '.js', '.mjs', '.cjs']);
const SKIPPED_DIRECTORIES = new Set(['node_modules', 'dist']);
const TEST_FILE_PATTERN = /\.test\.[cm]?[jt]sx?$/;

function normalizePluginSdkSpecifier(specifier) {
  if (typeof specifier !== 'string') return null;
  const match = PLUGIN_SDK_SPECIFIER_PATTERN.exec(specifier.trim());
  return match ? `openclaw/plugin-sdk${match[1] || ''}` : null;
}

function scriptKindForFile(ts, fileName) {
  switch (path.extname(fileName).toLowerCase()) {
    case '.tsx':
      return ts.ScriptKind.TSX;
    case '.js':
    case '.mjs':
    case '.cjs':
      return ts.ScriptKind.JS;
    default:
      return ts.ScriptKind.TS;
  }
}

function bindingElementImportName(ts, element) {
  if (element.dotDotDotToken) return null;
  const source = element.propertyName || element.name;
  if (ts.isIdentifier(source) || ts.isStringLiteralLike(source)) return source.text;
  return null;
}

// `const { a, b: c } = await import('openclaw/plugin-sdk/x')` links a and b.
function collectAwaitedImportBindingNames(ts, callExpression) {
  let awaited = callExpression.parent;
  while (awaited && ts.isParenthesizedExpression(awaited)) awaited = awaited.parent;
  if (!awaited || !ts.isAwaitExpression(awaited)) return [];
  let declaration = awaited.parent;
  while (declaration && ts.isParenthesizedExpression(declaration)) declaration = declaration.parent;
  if (
    !declaration
    || !ts.isVariableDeclaration(declaration)
    || !ts.isObjectBindingPattern(declaration.name)
  ) {
    return [];
  }
  return declaration.name.elements
    .map(element => bindingElementImportName(ts, element))
    .filter(name => name !== null);
}

/**
 * Lists the runtime-linked plugin SDK imports of one source file.
 * Type-only imports are erased before linking and are ignored. `name` is null
 * when the file only needs the module to exist (namespace, side-effect or
 * opaque dynamic imports, `export *`).
 */
function collectPluginSdkImportsFromSource(sourceText, fileName) {
  const ts = require('typescript');
  const sourceFile = ts.createSourceFile(
    fileName,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    scriptKindForFile(ts, fileName),
  );
  const imports = [];
  const record = (node, specifier, name) => {
    const { line } = sourceFile.getLineAndCharacterOfPosition(node.getStart(sourceFile));
    imports.push({ file: fileName, line: line + 1, specifier, name });
  };
  const specifierOf = node => (
    node && ts.isStringLiteralLike(node) ? normalizePluginSdkSpecifier(node.text) : null
  );

  const visit = node => {
    if (ts.isImportDeclaration(node)) {
      const specifier = specifierOf(node.moduleSpecifier);
      const clause = node.importClause;
      if (specifier && !clause) {
        record(node, specifier, null);
      } else if (specifier && !clause.isTypeOnly) {
        if (clause.name) record(clause.name, specifier, 'default');
        const bindings = clause.namedBindings;
        if (bindings && ts.isNamespaceImport(bindings)) {
          record(bindings, specifier, null);
        } else if (bindings && ts.isNamedImports(bindings)) {
          for (const element of bindings.elements) {
            if (element.isTypeOnly) continue;
            record(element, specifier, (element.propertyName || element.name).text);
          }
        }
      }
    } else if (ts.isExportDeclaration(node)) {
      const specifier = specifierOf(node.moduleSpecifier);
      if (specifier && !node.isTypeOnly) {
        if (node.exportClause && ts.isNamedExports(node.exportClause)) {
          for (const element of node.exportClause.elements) {
            if (element.isTypeOnly) continue;
            record(element, specifier, (element.propertyName || element.name).text);
          }
        } else {
          record(node, specifier, null);
        }
      }
    } else if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
      const specifier = node.arguments.length > 0 ? specifierOf(node.arguments[0]) : null;
      if (specifier) {
        const names = collectAwaitedImportBindingNames(ts, node);
        if (names.length === 0) record(node, specifier, null);
        for (const name of names) record(node, specifier, name);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return imports;
}

function listLocalExtensionSourceFiles(extensionsDir) {
  const files = [];
  const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort(byName)) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (SKIPPED_DIRECTORIES.has(entry.name) || entry.name.startsWith('.')) continue;
        walk(fullPath);
        continue;
      }
      if (!entry.isFile()) continue;
      if (
        !SOURCE_EXTENSIONS.has(path.extname(entry.name))
        || entry.name.endsWith('.d.ts')
        || TEST_FILE_PATTERN.test(entry.name)
      ) {
        continue;
      }
      files.push(fullPath);
    }
  };
  if (fs.existsSync(extensionsDir)) walk(extensionsDir);
  return files;
}

function collectLocalExtensionPluginSdkImports(extensionsDir, baseDir) {
  const base = baseDir || path.dirname(extensionsDir);
  const imports = [];
  for (const file of listLocalExtensionSourceFiles(extensionsDir)) {
    const relative = path.relative(base, file).split(path.sep).join('/');
    imports.push(...collectPluginSdkImportsFromSource(fs.readFileSync(file, 'utf8'), relative));
  }
  return imports;
}

function readPinnedOpenClawVersion(projectRoot) {
  const pkg = JSON.parse(fs.readFileSync(path.join(projectRoot || rootDir, 'package.json'), 'utf8'));
  const version = pkg.openclaw && pkg.openclaw.version;
  if (typeof version !== 'string' || !version) {
    throw new Error(`${LOG_PREFIX} Missing "openclaw.version" in package.json.`);
  }
  return version;
}

function findBuiltOpenClawRuntimeRoot(projectRoot) {
  const candidate = path.join(projectRoot || rootDir, 'vendor', 'openclaw-runtime', 'current');
  if (!fs.existsSync(path.join(candidate, 'package.json'))) return null;
  return fs.realpathSync(candidate);
}

function readRuntimeBuildInfo(runtimeRoot) {
  const infoPath = path.join(runtimeRoot, 'runtime-build-info.json');
  if (!fs.existsSync(infoPath)) return null;
  try {
    return JSON.parse(fs.readFileSync(infoPath, 'utf8'));
  } catch {
    return null;
  }
}

function readHostPackage(runtimeRoot) {
  const host = JSON.parse(fs.readFileSync(path.join(runtimeRoot, 'package.json'), 'utf8'));
  if (host.name !== HOST_PEER_PACKAGE_NAME || !host.exports || typeof host.exports !== 'object') {
    throw new Error(`${LOG_PREFIX} ${runtimeRoot} is not a built OpenClaw runtime.`);
  }
  return host;
}

/**
 * Resolves `openclaw/plugin-sdk/<name>` to its runtime file, e.g.
 * `dist/plugin-sdk/<name>.js`, through the host package exports map. Returns
 * null when the host does not export the subpath at all.
 */
function resolvePluginSdkTarget(hostPackage, specifier) {
  const subpath = `.${specifier.slice(HOST_PEER_PACKAGE_NAME.length)}`;
  const entry = hostPackage.exports ? hostPackage.exports[subpath] : undefined;
  if (entry === undefined) return null;
  // Mirror scripts/openclaw-plugin-sdk-bridge.cjs: the pinned host declares a
  // direct target or { types?, default }. Fail on new runtime conditions rather
  // than silently changing resolution.
  if (typeof entry !== 'string' && (!entry || Array.isArray(entry)
    || Object.keys(entry).some(key => key !== 'types' && key !== 'default'))) {
    throw new Error(`${LOG_PREFIX} Unsupported SDK export: ${subpath}`);
  }
  const target = typeof entry === 'string' ? entry : entry.default;
  if (typeof target !== 'string' || !/^\.\/dist\/plugin-sdk\/[\w/-]+\.m?js$/.test(target)) {
    throw new Error(`${LOG_PREFIX} Invalid SDK target for ${subpath}: ${target}`);
  }
  return target.slice('./'.length);
}

/** Reads each module's sorted export names without evaluating the SDK. */
function readPluginSdkExportTables(runtimeRoot, targets) {
  const tables = new Map();
  if (targets.length === 0) return tables;
  const esbuild = require('esbuild');
  const root = fs.realpathSync(runtimeRoot);
  const entryPoints = targets.map(target => path.join(root, target));
  for (const entryPoint of entryPoints) {
    if (!fs.existsSync(entryPoint)) {
      throw new Error(`${LOG_PREFIX} Missing SDK module: ${entryPoint}`);
    }
  }
  const { metafile } = esbuild.buildSync({
    absWorkingDir: root,
    entryPoints,
    outdir: path.join(os.tmpdir(), 'lobsterai-plugin-sdk-contract'),
    bundle: false,
    write: false,
    metafile: true,
    platform: 'node',
    format: 'esm',
    logLevel: 'silent',
  });
  const exportsByEntry = new Map();
  for (const output of Object.values(metafile.outputs)) {
    if (!output.entryPoint) continue;
    exportsByEntry.set(
      fs.realpathSync(path.resolve(root, output.entryPoint)),
      [...output.exports].sort(),
    );
  }
  targets.forEach((target, index) => {
    const exportNames = exportsByEntry.get(fs.realpathSync(entryPoints[index]));
    if (!exportNames) {
      throw new Error(`${LOG_PREFIX} esbuild produced no export table for ${target}`);
    }
    tables.set(target, exportNames);
  });
  return tables;
}

/**
 * Builds the snapshot for every SDK module the local extensions import.
 * Modules the host does not export are recorded with a null target so the
 * verification reports them precisely.
 */
function buildPluginSdkExportsSnapshot({ runtimeRoot, imports, openclawVersion }) {
  const hostPackage = readHostPackage(runtimeRoot);
  const specifiers = [...new Set(imports.map(entry => entry.specifier))].sort();
  const targets = new Map();
  for (const specifier of specifiers) {
    targets.set(specifier, resolvePluginSdkTarget(hostPackage, specifier));
  }
  const tables = readPluginSdkExportTables(
    runtimeRoot,
    [...new Set([...targets.values()].filter(target => target !== null))],
  );
  const modules = {};
  for (const [specifier, target] of targets) {
    modules[specifier] = target === null
      ? { target: null, exports: [] }
      : { target, exports: tables.get(target) };
  }
  return { $comment: SNAPSHOT_COMMENT, openclawVersion, modules };
}

function serializePluginSdkExportsSnapshot(snapshot) {
  return `${JSON.stringify(snapshot, null, 2)}\n`;
}

function readPluginSdkExportsSnapshot(projectRoot) {
  const snapshotPath = path.join(projectRoot || rootDir, SNAPSHOT_RELATIVE_PATH);
  if (!fs.existsSync(snapshotPath)) return null;
  return JSON.parse(fs.readFileSync(snapshotPath, 'utf8'));
}

/** Returns one problem per broken import, empty when every import links. */
function verifyPluginSdkImports(imports, snapshot) {
  const problems = new Set();
  const modules = snapshot && snapshot.modules && typeof snapshot.modules === 'object'
    ? snapshot.modules
    : {};
  for (const entry of imports) {
    const module = modules[entry.specifier];
    const location = `${entry.file}:${entry.line}`;
    if (!module) {
      problems.add(
        `${location}: "${entry.specifier}" is not in ${SNAPSHOT_RELATIVE_PATH}; `
        + 'rebuild the runtime and run `npm run openclaw:sdk-contract`.',
      );
      continue;
    }
    if (module.target === null) {
      problems.add(
        `${location}: the pinned OpenClaw runtime does not export the plugin SDK module "${entry.specifier}".`,
      );
      continue;
    }
    if (entry.name !== null && !module.exports.includes(entry.name)) {
      problems.add(
        `${location}: "${entry.specifier}" does not export "${entry.name}" in the pinned OpenClaw runtime.`,
      );
    }
  }
  return [...problems];
}

function main(argv) {
  const args = argv.slice(2);
  const check = args.includes('--check');
  const runtimeArg = args.find(arg => !arg.startsWith('--'));
  const runtimeRoot = runtimeArg
    ? fs.realpathSync(path.resolve(runtimeArg))
    : findBuiltOpenClawRuntimeRoot(rootDir);
  if (!runtimeRoot) {
    console.error(`${LOG_PREFIX} Built OpenClaw runtime not found at vendor/openclaw-runtime/current. Run \`npm run openclaw:runtime:host\` first.`);
    return 1;
  }

  const openclawVersion = readPinnedOpenClawVersion(rootDir);
  const buildInfo = readRuntimeBuildInfo(runtimeRoot);
  if (buildInfo && buildInfo.openclawVersion && buildInfo.openclawVersion !== openclawVersion) {
    console.error(`${LOG_PREFIX} Runtime at ${runtimeRoot} is ${buildInfo.openclawVersion}; package.json pins ${openclawVersion}. Rebuild the runtime first.`);
    return 1;
  }

  const imports = collectLocalExtensionPluginSdkImports(
    path.join(rootDir, EXTENSIONS_RELATIVE_DIR),
    rootDir,
  );
  const snapshot = buildPluginSdkExportsSnapshot({ runtimeRoot, imports, openclawVersion });
  const serialized = serializePluginSdkExportsSnapshot(snapshot);
  const snapshotPath = path.join(rootDir, SNAPSHOT_RELATIVE_PATH);
  const existing = fs.existsSync(snapshotPath) ? fs.readFileSync(snapshotPath, 'utf8') : null;
  const problems = verifyPluginSdkImports(imports, snapshot);

  let status = 0;
  if (check) {
    if (existing === serialized) {
      console.log(`${LOG_PREFIX} ${SNAPSHOT_RELATIVE_PATH} matches the built runtime.`);
    } else {
      console.error(`${LOG_PREFIX} ${SNAPSHOT_RELATIVE_PATH} is ${existing === null ? 'missing' : 'stale'}. Run \`npm run openclaw:sdk-contract\`.`);
      status = 1;
    }
  } else if (existing === serialized) {
    console.log(`${LOG_PREFIX} ${SNAPSHOT_RELATIVE_PATH} is up to date (${Object.keys(snapshot.modules).length} module(s)).`);
  } else {
    fs.writeFileSync(snapshotPath, serialized, 'utf8');
    console.log(`${LOG_PREFIX} Wrote ${SNAPSHOT_RELATIVE_PATH} (${Object.keys(snapshot.modules).length} module(s)).`);
  }

  for (const problem of problems) {
    console.error(`${LOG_PREFIX} ${problem}`);
  }
  if (problems.length > 0) {
    console.error(`${LOG_PREFIX} ${problems.length} plugin SDK import(s) would fail to link in the pinned runtime.`);
    status = 1;
  }
  return status;
}

if (require.main === module) {
  process.exit(main(process.argv));
}

module.exports = {
  EXTENSIONS_RELATIVE_DIR,
  SNAPSHOT_RELATIVE_PATH,
  buildPluginSdkExportsSnapshot,
  collectLocalExtensionPluginSdkImports,
  collectPluginSdkImportsFromSource,
  findBuiltOpenClawRuntimeRoot,
  listLocalExtensionSourceFiles,
  normalizePluginSdkSpecifier,
  readPinnedOpenClawVersion,
  readPluginSdkExportTables,
  readPluginSdkExportsSnapshot,
  readRuntimeBuildInfo,
  resolvePluginSdkTarget,
  serializePluginSdkExportsSnapshot,
  verifyPluginSdkImports,
};
