'use strict';

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');
const { HOST_PEER_PACKAGE_NAME } = require('./openclaw-plugin-host-peer-leftovers.cjs');

const SDK_BRIDGE_LOCATION = path.join('node_modules', HOST_PEER_PACKAGE_NAME);
const SDK_BRIDGE_MARKER = 'lobsteraiPluginSdkBridge';
const SDK_BRIDGE_VERSION = 1;

function isInside(root, target) {
  const relative = path.relative(root, target);
  return relative !== '' && !relative.startsWith('..') && !path.isAbsolute(relative);
}

/**
 * Hoist a tiny SDK package for plugins whose private openclaw peer was pruned.
 * Re-exports preserve the host's module instances, including runtime state.
 * Ordinary files and relative imports survive tar/copy/signing/relocation;
 * a host symlink would be expanded by the Windows tar packer's follow:true.
 */
function planSdkBridge(runtimeRoot) {
  const root = fs.realpathSync(runtimeRoot);
  const bridgeDir = path.join(root, SDK_BRIDGE_LOCATION);
  const host = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  if (host.name !== HOST_PEER_PACKAGE_NAME || !host.exports || typeof host.exports !== 'object') {
    throw new Error('[openclaw-sdk-bridge] Missing OpenClaw host exports. Rebuild the runtime.');
  }

  const targets = new Map();
  const exports = {};
  for (const [subpath, entry] of Object.entries(host.exports)) {
    if (subpath !== './plugin-sdk' && !subpath.startsWith('./plugin-sdk/')) continue;
    // The pinned host declares either a direct target or { types?, default }.
    // Fail on new runtime conditions rather than silently changing resolution.
    if (typeof entry !== 'string' && (!entry || Array.isArray(entry)
      || Object.keys(entry).some(key => key !== 'types' && key !== 'default'))) {
      throw new Error(`[openclaw-sdk-bridge] Unsupported SDK export: ${subpath}`);
    }
    const target = typeof entry === 'string' ? entry : entry.default;
    if (typeof target !== 'string' || !/^\.\/dist\/plugin-sdk\/[\w/-]+\.m?js$/.test(target)) {
      throw new Error(`[openclaw-sdk-bridge] Invalid SDK target for ${subpath}: ${target}`);
    }
    const targetPath = path.join(root, target);
    if (!fs.existsSync(targetPath) || !isInside(root, fs.realpathSync(targetPath))) {
      throw new Error(`[openclaw-sdk-bridge] Missing or external SDK target: ${targetPath}`);
    }
    const wrapper = target.slice('./dist/'.length);
    targets.set(fs.realpathSync(targetPath), wrapper);
    exports[subpath] = `./${wrapper}`;
  }
  if (targets.size === 0) throw new Error('[openclaw-sdk-bridge] No SDK exports found.');

  // Parse exports without evaluating the SDK or bundling/copying its dependencies.
  const { metafile } = esbuild.buildSync({
    entryPoints: [...targets.keys()],
    outdir: path.join(bridgeDir, '.metadata'),
    bundle: false,
    write: false,
    metafile: true,
    platform: 'node',
    format: 'esm',
    logLevel: 'silent',
  });
  const files = new Map();
  for (const output of Object.values(metafile.outputs)) {
    const targetPath = fs.realpathSync(path.resolve(output.entryPoint));
    const wrapper = targets.get(targetPath);
    const relative = path.relative(path.dirname(path.join(bridgeDir, wrapper)), targetPath)
      .split(path.sep).join('/');
    const specifier = JSON.stringify(relative);
    files.set(wrapper, [
      '// Generated by LobsterAI. Reuse the bundled OpenClaw SDK.',
      `export * from ${specifier};`,
      ...(output.exports.includes('default') ? [`export { default } from ${specifier};`] : []),
      '',
    ].join('\n'));
  }
  files.set('package.json', JSON.stringify({
    name: HOST_PEER_PACKAGE_NAME,
    version: host.version,
    private: true,
    type: 'module',
    [SDK_BRIDGE_MARKER]: SDK_BRIDGE_VERSION,
    exports,
  }, null, 2) + '\n');
  return { root, bridgeDir, files, exportCount: Object.keys(exports).length };
}

function readBridgeFiles(bridgeDir) {
  const files = new Map();
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isSymbolicLink()) {
        throw new Error(`[openclaw-sdk-bridge] SDK bridge must not contain links: ${fullPath}`);
      }
      if (entry.isDirectory()) walk(fullPath);
      else files.set(path.relative(bridgeDir, fullPath).split(path.sep).join('/'), fs.readFileSync(fullPath, 'utf8'));
    }
  }
  walk(bridgeDir);
  return files;
}

function bridgeMatches(plan) {
  const existing = readBridgeFiles(plan.bridgeDir);
  return existing.size === plan.files.size
    && [...plan.files].every(([file, content]) => existing.get(file) === content);
}

function assertOwnedBridge(plan) {
  const nodeModules = path.dirname(plan.bridgeDir);
  if (!isInside(plan.root, fs.realpathSync(nodeModules))) {
    throw new Error('[openclaw-sdk-bridge] Runtime node_modules points outside the runtime.');
  }
  let stat;
  try { stat = fs.lstatSync(plan.bridgeDir); } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
  if (!stat.isDirectory() || stat.isSymbolicLink()) {
    throw new Error(`[openclaw-sdk-bridge] Refusing to replace a host link: ${plan.bridgeDir}`);
  }
  const manifestPath = path.join(plan.bridgeDir, 'package.json');
  const manifest = fs.existsSync(manifestPath)
    ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : {};
  if (manifest[SDK_BRIDGE_MARKER] !== SDK_BRIDGE_VERSION) {
    throw new Error(`[openclaw-sdk-bridge] Refusing to replace an unmanaged host package: ${plan.bridgeDir}`);
  }
  return true;
}

function ensureOpenClawPluginSdkBridge(runtimeRoot) {
  const plan = planSdkBridge(runtimeRoot);
  fs.mkdirSync(path.dirname(plan.bridgeDir), { recursive: true });
  const exists = assertOwnedBridge(plan);
  const changed = !exists || !bridgeMatches(plan);
  if (changed) {
    // Only the generated bridge inside this runtime is replaced, never a host copy/link.
    if (exists) fs.rmSync(plan.bridgeDir, { recursive: true, force: true });
    for (const [file, content] of plan.files) {
      const target = path.join(plan.bridgeDir, file);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content, 'utf8');
    }
  }
  return {
    changed,
    exportCount: plan.exportCount,
    files: plan.files.size,
    bytes: [...plan.files.values()].reduce((sum, content) => sum + Buffer.byteLength(content), 0),
  };
}

function verifyOpenClawPluginSdkBridge(runtimeRoot) {
  const plan = planSdkBridge(runtimeRoot);
  if (!assertOwnedBridge(plan) || !bridgeMatches(plan)) {
    throw new Error('[openclaw-sdk-bridge] SDK bridge is missing or stale. Run `npm run openclaw:prune` before packaging.');
  }
}

module.exports = { SDK_BRIDGE_LOCATION, ensureOpenClawPluginSdkBridge, verifyOpenClawPluginSdkBridge };
