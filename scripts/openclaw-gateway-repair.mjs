// Manual one-click repair entry. Do not invoke this from normal startup.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { repairOpenClawCompatibility } from '../src/main/libs/openclawCompatibilityRepairCore.ts';
import { OPENCLAW_REPAIR_RESULT_PREFIX, OpenClawRepairPhase } from '../src/shared/openclawEngine/repair.ts';
import { recoverOpenClawLockOwners } from '../src/main/libs/openclawLockRecovery.ts';
import { acquireGatewayLock } from '#openclaw-gateway-lock';
import { withDoctorSqliteMaintenanceLock } from '#openclaw-repair-lock';
import { assertOpenClawDatabasesReady } from '#openclaw-repair-schema-check';
import { assertOpenClawStateDatabaseForMaintenance } from '#openclaw-repair-state-check';
import { resolveConfiguredAgentDatabaseTargets } from '#openclaw-repair-agent-targets';
import { loadSqliteVecExtension } from '#openclaw-repair-vectors';
import { loadInstalledPluginIndexInstallRecordsSync, writePersistedInstalledPluginIndexInstallRecordsSync } from '#openclaw-repair-plugin-records';
import { runPluginPayloadSmokeCheckForManifestRecords } from '#openclaw-repair-plugin-payload';
import { resolvePluginCapabilityConsent } from '#openclaw-repair-plugin-consent';

const runtimeRoot = path.dirname(fileURLToPath(import.meta.url));
const request = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const env = process.env;
if (![env.OPENCLAW_STATE_DIR, env.OPENCLAW_CONFIG_PATH, env.OPENCLAW_HOME, request.backupDir].every(value => value && path.isAbsolute(value))) {
  throw new Error('Manual repair requires explicit absolute state, config, home and backup paths.');
}
const manifest = JSON.parse(fs.readFileSync(path.join(runtimeRoot, 'lobsterai-repair-plugins.json'), 'utf8'));
const runtimeVersion = JSON.parse(fs.readFileSync(path.join(runtimeRoot, 'package.json'), 'utf8')).version;
if (runtimeVersion !== manifest.openclawVersion) throw new Error('Manual repair helper does not match the bundled OpenClaw version.');
const options = {
  ...request, stateDir: env.OPENCLAW_STATE_DIR, configPath: env.OPENCLAW_CONFIG_PATH,
  plugins: manifest.plugins.map(plugin => ({ ...plugin, root: path.join(runtimeRoot, plugin.relativePath) })),
};
const report = request.phase === OpenClawRepairPhase.LockRecovery
  ? await recoverOpenClawLockOwners({ ...options, runtimeRoot, executablePath: process.execPath, env }, { acquireLock: acquireGatewayLock })
  : await repairOpenClawCompatibility(options, {
  withLock: run => withDoctorSqliteMaintenanceLock({ env, operation: 'LobsterAI one-click repair', run }),
  verifyDatabaseSchemas() {
    const pathname = path.join(env.OPENCLAW_STATE_DIR, 'state', 'openclaw.sqlite');
    if (fs.existsSync(pathname)) {
      const db = new DatabaseSync(pathname, { readOnly: true });
      try { assertOpenClawStateDatabaseForMaintenance(db, { pathname }); } finally { db.close(); }
    }
    let config = {};
    try { config = JSON.parse(fs.readFileSync(env.OPENCLAW_CONFIG_PATH, 'utf8')); } catch { /* regenerated by the app */ }
    assertOpenClawDatabasesReady({
      env, operation: 'doctor', configuredAgentDatabaseTargets: resolveConfiguredAgentDatabaseTargets(config, { env }),
    });
  },
  async loadVectorExtension(db) {
    const result = await loadSqliteVecExtension({ db });
    if (!result.ok) throw new Error(result.error || 'The bundled sqlite-vec extension could not be loaded.');
  },
  readInstallRecords: () => loadInstalledPluginIndexInstallRecordsSync({ env }),
  writeInstallRecords: (records, config) => writePersistedInstalledPluginIndexInstallRecordsSync(records, { env, config }),
  async validatePlugin(id, root) {
    const result = await runPluginPayloadSmokeCheckForManifestRecords({ plugins: [{ id, rootDir: root }], env });
    let usesPackagedBridge = false;
    if (options.plugins.some(plugin => plugin.id === id && plugin.root === root)) {
      // LobsterAI deliberately packages one shared SDK bridge instead of npm's
      // per-plugin host junctions. Verify actual Node resolution of that bridge
      // before accepting this one layout-specific difference from npm installs.
      const bridgeRoot = path.join(runtimeRoot, 'node_modules', 'openclaw');
      const bridge = JSON.parse(fs.readFileSync(path.join(bridgeRoot, 'package.json'), 'utf8'));
      const resolvedSdk = createRequire(path.join(root, 'package.json')).resolve('openclaw/plugin-sdk/core');
      usesPackagedBridge = bridge.lobsteraiPluginSdkBridge === 1 && bridge.version === runtimeVersion
        && resolvedSdk === path.join(bridgeRoot, 'plugin-sdk', 'core.js');
    }
    const failures = result.failures.filter(failure => !usesPackagedBridge || failure.reason !== 'missing-openclaw-peer-link');
    if (failures.length) throw new Error(failures.map(failure => failure.detail).join('\n'));
  },
  acceptBundledPlugin: (pluginId, config) => resolvePluginCapabilityConsent({
    pluginId, config, env,
    // Only called after identity/version and static payload validation against
    // the app's build-time manifest. No user-installed package gets this grant.
    onCapabilityConsent: async review => ({ reviewToken: review.reviewToken }),
  }),
});
console.log(OPENCLAW_REPAIR_RESULT_PREFIX + JSON.stringify(report));
process.exitCode = report.success ? 0 : 1;
