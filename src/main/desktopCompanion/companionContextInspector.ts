const MARKER = '@@LOBSTER_CTX ';
const MAC_QUERY_TIMEOUT_MS = 350;
const WIN_QUERY_TIMEOUT_MS = 800;
const MAX_TRACKED_FINGERPRINTS = 64;
const CLIPBOARD_PREVIEW_MAX_CHARS = 36;
const IMAGE_FILE_PATTERN = /\.(png|jpe?g|webp|gif|bmp|heic)$/i;

/** Pasteboard/clipboard markers set by password managers and transient tools. */
const CONCEALED_CLIPBOARD_FORMATS: readonly string[] = [
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
  'com.agilebits.onepassword',
  'de.petermaurer.TransientPasteboardType',
  'com.typeit4me.clipping',
  'ExcludeClipboardContentFromMonitorProcessing',
  'CanIncludeInClipboardHistory',
];

const WINDOWS_ACTIVE_FILE_APPS: ReadonlySet<string> = new Set([
  'explorer.exe',
  'winword.exe',
  'excel.exe',
  'powerpnt.exe',
]);

export interface ClipboardProbeImage {
  kind: typeof CompanionContextClipboardKind.Image;
  fingerprint: string;
  width: number;
  height: number;
  toPNG(): Buffer;
}

export interface ClipboardProbeText {
  kind: typeof CompanionContextClipboardKind.Text;
  fingerprint: string;
  text: string;
}

export type ClipboardProbeResult =
  | { kind: 'concealed' }
  | { kind: 'empty' }
  | ClipboardProbeImage
  | ClipboardProbeText;

export interface ContextInspectorDeps {
  platform?: NodeJS.Platform;
  isAccessibilityTrusted?: () => boolean;
  readClipboard?: () => ClipboardProbeResult;
  saveClipboardImage?: (pngBuffer: Buffer) => Promise<string>;
  queryActiveFile?: (appId: string, category: CompanionAppCategory, pid?: number | null) => Promise<string | null>;
  statPath?: (targetPath: string) => { isDirectory: boolean } | null;
  now?: () => number;
}

export function hashFingerprint(prefix: string, payload: string | Buffer): string {
  return `${prefix}:${createHash('sha256').update(payload).digest('hex').slice(0, 24)}`;
}

/**
 * One-shot macOS JXA query using Accessibility (AXDocument / AXProxy->AXURL).
 * Never sends Apple Events, so it never triggers macOS Automation prompts.
 */
export function macActiveDocumentScript(bundleId: string, pid?: number | null): string {
  const safeBundleId = JSON.stringify(bundleId);
  const safePid = typeof pid === 'number' && Number.isSafeInteger(pid) && pid > 0 ? pid : 0;
  return `
ObjC.import('ApplicationServices');
ObjC.import('AppKit');
function emit(value) { console.log('${MARKER}' + JSON.stringify({ path: value })); }
function axAttr(el, name) {
  var ref = Ref();
  if ($.AXUIElementCopyAttributeValue(el, $(name), ref) !== 0) return null;
  return ref[0];
}
function unwrapUrl(val) {
  if (!val) return null;
  try {
    if (typeof val === 'string') return val;
    if (typeof val.isNil === 'function' && val.isNil()) return null;
    if (typeof val.isKindOfClass === 'function' && val.isKindOfClass($.NSURL)) return ObjC.unwrap(val.absoluteString);
    if (typeof val.isKindOfClass === 'function' && val.isKindOfClass($.NSString)) return ObjC.unwrap(val);
    var unwrapped = ObjC.unwrap(val);
    return typeof unwrapped === 'string' ? unwrapped : null;
  } catch (e) {
    return null;
  }
}
try {
  var pid = ${safePid};
  if (pid <= 0) {
    var apps = $.NSRunningApplication.runningApplicationsWithBundleIdentifier($(${safeBundleId}));
    if (!apps.isNil() && Number(apps.count) > 0) pid = Number(apps.objectAtIndex(0).processIdentifier);
  }
  if (pid <= 0) { emit(null); }
  else {
    var axApp = $.AXUIElementCreateApplication(pid);
    var win = axAttr(axApp, 'AXFocusedWindow') || axAttr(axApp, 'AXMainWindow');
    if (!win) {
      var list = axAttr(axApp, 'AXWindows');
      if (list && (typeof list.isNil !== 'function' || !list.isNil()) && Number(list.count) > 0) win = list.objectAtIndex(0);
    }
    var found = null;
    if (win) {
      found = unwrapUrl(axAttr(win, 'AXDocument'));
      if (!found) {
        var proxy = axAttr(win, 'AXProxy');
        if (proxy) found = unwrapUrl(axAttr(proxy, 'AXURL'));
      }
    }
    emit(found);
  }
} catch (e) {
  emit(null);
}
`;
}

/** One-shot Windows PowerShell query for Explorer folder or Office active document path. */
export function windowsActiveDocumentScript(executable: string): string | null {
  const id = normalizeCompanionAppId(executable);
  if (id === 'explorer.exe') {
    return `
$sig = '[DllImport("user32.dll")] public static extern IntPtr GetForegroundWindow();'
$u32 = Add-Type -MemberDefinition $sig -Name 'LobsterU32' -Namespace 'Win32' -PassThru
$fg = $u32::GetForegroundWindow().ToInt64()
$shell = New-Object -ComObject Shell.Application
foreach ($w in $shell.Windows()) {
  try {
    if ([int64]$w.HWND -eq $fg) {
      $p = $w.Document.Folder.Self.Path
      if ($p) { Write-Output ('${MARKER}' + (@{ path = $p } | ConvertTo-Json -Compress)); break }
    }
  } catch {}
}
`;
  }
  const progIds: Record<string, { progId: string; expr: string }> = {
    'winword.exe': { progId: 'Word.Application', expr: '$app.ActiveDocument.FullName' },
    'excel.exe': { progId: 'Excel.Application', expr: '$app.ActiveWorkbook.FullName' },
    'powerpnt.exe': { progId: 'PowerPoint.Application', expr: '$app.ActivePresentation.FullName' },
  };
  const target = progIds[id];
  if (!target) return null;
  return `
try {
  $app = [Runtime.InteropServices.Marshal]::GetActiveObject('${target.progId}')
  $p = ${target.expr}
  if ($p) { Write-Output ('${MARKER}' + (@{ path = $p } | ConvertTo-Json -Compress)) }
} catch {}
`;
}

export function parseActiveDocumentOutput(output: string): string | null {
  for (const line of output.split(/\r?\n/)) {
    const idx = line.indexOf(MARKER);
    if (idx < 0) continue;
    try {
      const parsed = JSON.parse(line.slice(idx + MARKER.length)) as { path?: unknown };
      return typeof parsed.path === 'string' && parsed.path.trim() ? parsed.path.trim() : null;
    } catch {
      return null;
    }
  }
  return null;
}

function defaultReadClipboard(): ClipboardProbeResult {
  try {
    const formats = clipboard.availableFormats().map(item => item.toLowerCase());
    for (const marker of CONCEALED_CLIPBOARD_FORMATS) {
      if (formats.includes(marker.toLowerCase()) || clipboard.has(marker)) {
        return { kind: 'concealed' };
      }
    }
    const hasImage = formats.some(item => item.startsWith('image/'));
    if (hasImage) {
      const image = clipboard.readImage();
      if (!image.isEmpty()) {
        const size = image.getSize();
        if (size.width >= COMPANION_CLIPBOARD_MIN_IMAGE_PX && size.height >= COMPANION_CLIPBOARD_MIN_IMAGE_PX) {
          const thumb = image.resize({ width: Math.min(64, size.width) }).toBitmap();
          const fingerprint = hashFingerprint(`img:${size.width}x${size.height}`, thumb);
          return {
            kind: CompanionContextClipboardKind.Image,
            fingerprint,
            width: size.width,
            height: size.height,
            toPNG: () => image.toPNG(),
          };
        }
      }
    }
    const rawText = clipboard.readText();
    const trimmed = rawText.trim();
    if (!trimmed) return { kind: 'empty' };
    return {
      kind: CompanionContextClipboardKind.Text,
      fingerprint: hashFingerprint('txt', trimmed),
      text: trimmed,
    };
  } catch {
    return { kind: 'empty' };
  }
}

async function defaultSaveClipboardImage(pngBuffer: Buffer): Promise<string> {
  const directory = path.join(app.getPath('temp'), 'lobsterai', 'attachments');
  await fsPromises.mkdir(directory, { recursive: true });
  const filePath = path.join(directory, `clipboard-${randomUUID()}.png`);
  await fsPromises.writeFile(filePath, pngBuffer, { mode: 0o600 });
  return filePath;
}

function defaultStatPath(targetPath: string): { isDirectory: boolean } | null {
  try {
    const stat = fs.statSync(targetPath);
    return { isDirectory: stat.isDirectory() };
  } catch {
    return null;
  }
}

function defaultQueryActiveFile(
  platform: NodeJS.Platform,
  isTrusted: () => boolean,
): (appId: string, category: CompanionAppCategory, pid?: number | null) => Promise<string | null> {
  return (appId, category, pid) => {
    if (!supportsActiveFileInspection(category)) return Promise.resolve(null);
    if (platform === 'darwin') {
      if (!isTrusted()) return Promise.resolve(null);
      const script = macActiveDocumentScript(appId, pid);
      return new Promise(resolve => {
        execFile('/usr/bin/osascript', ['-l', 'JavaScript', '-e', script], { timeout: MAC_QUERY_TIMEOUT_MS }, (error, stdout, stderr) => {
          if (error) { resolve(null); return; }
          resolve(parseActiveDocumentOutput(`${stderr ?? ''}\n${stdout ?? ''}`));
        });
      });
    }
    if (platform === 'win32') {
      const id = normalizeCompanionAppId(appId);
      if (!WINDOWS_ACTIVE_FILE_APPS.has(id)) return Promise.resolve(null);
      const script = windowsActiveDocumentScript(id);
      if (!script) return Promise.resolve(null);
      return new Promise(resolve => {
        execFile('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', script], {
          timeout: WIN_QUERY_TIMEOUT_MS,
          windowsHide: true,
        }, (error, stdout) => {
          if (error) { resolve(null); return; }
          resolve(parseActiveDocumentOutput(stdout ?? ''));
        });
      });
    }
    return Promise.resolve(null);
  };
}

function rememberBounded(set: Set<string>, value: string): void {
  if (!value) return;
  if (set.has(value)) set.delete(value);
  set.add(value);
  while (set.size > MAX_TRACKED_FINGERPRINTS) {
    const oldest = set.values().next().value;
    if (oldest !== undefined) set.delete(oldest);
    else break;
  }
}

/**
 * On-demand foreground context inspector (zero background polling).
 * Called only when the user opens the quick panel or hover launcher.
 */
export class CompanionContextInspector {
  private readonly platform: NodeJS.Platform;
  private readonly isAccessibilityTrusted: () => boolean;
  private readonly readClipboard: () => ClipboardProbeResult;
  private readonly saveClipboardImage: (pngBuffer: Buffer) => Promise<string>;
  private readonly queryActiveFile: (appId: string, category: CompanionAppCategory, pid?: number | null) => Promise<string | null>;
  private readonly statPath: (targetPath: string) => { isDirectory: boolean } | null;
  private readonly now: () => number;
  private readonly blockedFingerprints = new Set<string>();
  private readonly consumedFingerprints = new Set<string>();

  constructor(deps: ContextInspectorDeps = {}) {
    this.platform = deps.platform ?? process.platform;
    this.isAccessibilityTrusted = deps.isAccessibilityTrusted ?? (() => (
      this.platform === 'darwin' ? systemPreferences.isTrustedAccessibilityClient(false) : true
    ));
    this.readClipboard = deps.readClipboard ?? defaultReadClipboard;
    this.saveClipboardImage = deps.saveClipboardImage ?? defaultSaveClipboardImage;
    this.queryActiveFile = deps.queryActiveFile ?? defaultQueryActiveFile(this.platform, this.isAccessibilityTrusted);
    this.statPath = deps.statPath ?? defaultStatPath;
    this.now = deps.now ?? Date.now;
  }

  /** Marks whatever was already on the clipboard at startup so stale items are not surfaced as newly copied. */
  captureBaselineClipboard(): void {
    const probe = this.readClipboard();
    if (probe.kind === CompanionContextClipboardKind.Text || probe.kind === CompanionContextClipboardKind.Image) {
      rememberBounded(this.consumedFingerprints, probe.fingerprint);
    }
  }

  /** Called when leaving a password manager so anything copied there can never be suggested later. */
  suppressCurrentClipboard(): void {
    const probe = this.readClipboard();
    if (probe.kind === CompanionContextClipboardKind.Text || probe.kind === CompanionContextClipboardKind.Image) {
      rememberBounded(this.blockedFingerprints, probe.fingerprint);
    }
  }

  dismissClipboard(fingerprint: string): void {
    rememberBounded(this.consumedFingerprints, fingerprint);
  }

  /** Synchronous fast snapshot used on frame 1 when opening the quick panel or launcher. */
  inspectSync(
    foreground: { appId: string; category: CompanionAppCategory } | null,
    includeClipboard: boolean,
  ): DesktopCompanionContextSnapshot | null {
    const category = foreground?.category ?? null;
    if (isContextSuggestionsBlocked(category)) return null;
    const clipboardMeta = includeClipboard ? this.inspectClipboard() : undefined;
    return {
      capturedAt: this.now(),
      appId: foreground?.appId ?? null,
      category,
      ...(clipboardMeta ? { clipboard: clipboardMeta } : {}),
    };
  }

  /** Async non-blocking lookup of the active local file or folder in the foreground app. */
  async resolveActiveFile(
    foreground: { appId: string; category: CompanionAppCategory; pid?: number | null } | null,
  ): Promise<DesktopCompanionContextFile | null> {
    if (!foreground || isContextSuggestionsBlocked(foreground.category) || !supportsActiveFileInspection(foreground.category)) {
      return null;
    }
    try {
      const raw = await this.queryActiveFile(foreground.appId, foreground.category, foreground.pid);
      if (!raw) return null;
      return this.validateLocalFile(raw);
    } catch {
      return null;
    }
  }

  validateLocalFile(rawPath: string): DesktopCompanionContextFile | null {
    const localPath = parseLocalFileReference(rawPath);
    if (!localPath) return null;
    const stat = this.statPath(localPath);
    if (!stat) return null;
    const name = path.basename(localPath) || localPath;
    const kind = stat.isDirectory ? CompanionFileKind.Folder : companionFileKindFromName(name);
    return {
      path: localPath,
      name,
      kind,
      isDirectory: stat.isDirectory,
      isImage: !stat.isDirectory && IMAGE_FILE_PATTERN.test(localPath),
    };
  }

  materializeClipboardText(expectedFingerprint?: string): { text: string; fingerprint: string } | null {
    const probe = this.readClipboard();
    if (probe.kind !== CompanionContextClipboardKind.Text) return null;
    if (expectedFingerprint && probe.fingerprint !== expectedFingerprint) return null;
    if (this.blockedFingerprints.has(probe.fingerprint)) return null;
    if (!isEligibleClipboardText(probe.text)) return null;
    rememberBounded(this.consumedFingerprints, probe.fingerprint);
    return { text: probe.text, fingerprint: probe.fingerprint };
  }

  async materializeClipboardImage(
    expectedFingerprint?: string,
  ): Promise<{ attachment: DesktopCompanionAttachment; fingerprint: string } | null> {
    const probe = this.readClipboard();
    if (probe.kind !== CompanionContextClipboardKind.Image) return null;
    if (expectedFingerprint && probe.fingerprint !== expectedFingerprint) return null;
    if (this.blockedFingerprints.has(probe.fingerprint)) return null;
    const png = probe.toPNG();
    if (!png || png.length === 0) return null;
    const filePath = await this.saveClipboardImage(png);
    rememberBounded(this.consumedFingerprints, probe.fingerprint);
    return {
      fingerprint: probe.fingerprint,
      attachment: {
        path: filePath,
        name: `${t('desktopCompanionClipboardImageName')}.png`,
        isImage: true,
        isDirectory: false,
      },
    };
  }

  private inspectClipboard(): DesktopCompanionContextClipboard | undefined {
    const probe = this.readClipboard();
    if (probe.kind === 'empty' || probe.kind === 'concealed') return undefined;
    if (this.blockedFingerprints.has(probe.fingerprint) || this.consumedFingerprints.has(probe.fingerprint)) {
      return undefined;
    }
    if (probe.kind === CompanionContextClipboardKind.Image) {
      return {
        kind: CompanionContextClipboardKind.Image,
        fingerprint: probe.fingerprint,
        width: probe.width,
        height: probe.height,
      };
    }
    if (!isEligibleClipboardText(probe.text)) return undefined;
    const preview = probe.text.replace(/\s+/g, ' ').slice(0, CLIPBOARD_PREVIEW_MAX_CHARS);
    return {
      kind: CompanionContextClipboardKind.Text,
      fingerprint: probe.fingerprint,
      charCount: probe.text.length,
      preview,
    };
  }
}
