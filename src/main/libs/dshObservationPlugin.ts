import * as fs from 'fs';
import * as path from 'path';
import { pathToFileURL } from 'url';

import { DSH_INSTANCE_HEADER, DSH_OBSERVER_READY_PREFIX } from '../../shared/dshEngine/analytics';

/** No imports or runtime dependencies: the generated ESM runs inside DSH. */
export function buildDshObservationPluginSource(): string {
  return `// Generated by LobsterAI. Optional, per-launch observation only.
export function apply(ctx, config) {
  try {
    const target = new URL(config.baseUrl);
    if (target.protocol !== 'http:' || target.hostname !== '127.0.0.1'
      || target.pathname !== '/v1' || target.search || target.hash
      || target.username || target.password || !target.port
      || !/^[a-f0-9-]{36}$/.test(config.instanceId)) return;
    ctx.on('llm-pi-ai/request-headers', (request, headers, next) => {
      // Only our contribution is guarded. Downstream exceptions keep their
      // original semantics, and next() must never be invoked twice.
      try {
        const actual = new URL(request.baseURL);
        if (actual.href.replace(/\\/$/, '') === target.href) {
          headers.set(${JSON.stringify(DSH_INSTANCE_HEADER)}, config.instanceId);
        }
      } catch { /* Observation must not fail inference. */ }
      return next();
    });
    console.log(${JSON.stringify(DSH_OBSERVER_READY_PREFIX)} + config.instanceId);
  } catch { /* Optional registration must not fail runtime startup. */ }
}
`;
}

/** Outside DSH_HOME, supplied only to this child via --patch. */
export function writeDshObservationPatch(directory: string, instanceId: string, baseUrl: string): string {
  const pluginPath = path.join(directory, 'observer.mjs');
  const patchPath = path.join(directory, 'observer.patch.json');
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(pluginPath, buildDshObservationPluginSource(), 'utf8');
  fs.writeFileSync(patchPath, JSON.stringify([{
    insert: [{
      id: 'lobsterai-dsh-observer',
      name: pathToFileURL(pluginPath).href,
      config: { instanceId, baseUrl },
    }],
  }]), 'utf8');
  return patchPath;
}
